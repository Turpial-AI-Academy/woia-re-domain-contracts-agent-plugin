import assert from 'node:assert/strict';
import { createNormalizationDescriptor, createLeasingOutcomeDescriptor,createAssetManagementOutcomeDescriptor,
  createDocumentLinkDescriptor,createSalesDomainDescriptor,createMarketingDomainDescriptor,
  domainDescriptorDigest,resolveRepresentationPolicy,resolveDocumentPresentation,resolveAdministrationResidualPolicy } from '../skills/woia-re-domain-contracts/scripts/domain-descriptors.mjs';
import { validateRelationCatalog } from '../skills/woia-re-domain-contracts/scripts/contracts.mjs';
const source={source_ref:'released-contract:sha256-immutable',revision:'1',org_id:'org:a',scope:'case:a'};
const normalization=createNormalizationDescriptor({...source,relation:'Property'});
assert.equal(normalization.target,'5NF');
assert.equal(Object.isFrozen(normalization),true);
assert.equal(normalization.authenticated,undefined);
assert.equal(normalization.accepted,undefined);
assert.throws(()=>createNormalizationDescriptor({...source,relation:'unknown'}),/UNKNOWN_RELATION/);
assert.throws(()=>createNormalizationDescriptor({...source,relation:'Property',target:'1NF'}),/UNSUPPORTED_DESCRIPTOR_INPUT/);
assert.throws(()=>createNormalizationDescriptor({...source,relation:'Property',org_id:''}),/EXACT_DESCRIPTOR_SCOPE_REQUIRED/);
const leasing=createLeasingOutcomeDescriptor({...source,subject_ref:'lease:a'});
assert.deepEqual(leasing.phases.agreement,['signature','initial_money','physical_handover']);
assert.deepEqual(leasing.phases.placement,['application_evidence','competent_decision']);
assert.deepEqual(leasing.phases.administration_transfer,['receiver_acceptance']);
assert.throws(()=>leasing.phases.agreement.push('different'),TypeError);
const administration=createAssetManagementOutcomeDescriptor({...source,subject_ref:'asset:a'});
assert.deepEqual(administration.phases.maintenance_outcome,['work_evidence','competent_acceptance']);
assert.deepEqual(administration.phases.administration_entry,['receiver_acceptance','source_position']);
const links=createDocumentLinkDescriptor();
assert.equal(links.target_types.find(t=>t.type==='Property').owner_provider,'woia-re-property-data');
assert.equal(links.target_types.find(t=>t.type==='LeaseVersion').relation,'DocumentLeaseLink');
assert.equal(links.target_types.find(t=>t.type==='MaintenanceCase').owner_provider,'woia-re-maintenance');
const sales=createSalesDomainDescriptor({...source,scope:'sales.pipeline'});
assert.equal(sales.entity,'Opportunity');
assert.equal(sales.domain_refs.find(t=>t.entity==='Offer').owner_plugin,'woia-re-transactions');
assert.equal(sales.domain_refs.find(t=>t.entity==='Payment').owner_plugin,'woia-payments');
assert.throws(()=>createSalesDomainDescriptor(source),/SALES_PIPELINE_SCOPE_REQUIRED/);
const marketing=createMarketingDomainDescriptor(source);
assert.deepEqual(marketing.allowed_operations,['publish','update-publication','withdraw-publication']);
assert.equal(marketing.public_non_person_only,true);
assert.equal(marketing.paid_allowed,false);
assert.deepEqual(marketing.outcome_requires,['remote-observation','listing-truth-acceptance-separate']);
const digest=domainDescriptorDigest(normalization);
assert.match(digest,/^[0-9a-f]{64}$/);
assert.equal(digest,domainDescriptorDigest(Object.fromEntries(Object.entries(normalization).reverse())));
assert.notEqual(digest,domainDescriptorDigest({...normalization,target:'3NF'}));
const representation=resolveRepresentationPolicy();
assert.deepEqual(representation.source_relations,['Mandate','MandateVersion','MandateAuthorityScope']);
assert.equal(representation.initial_human_boundaries.length,6);
assert.deepEqual(resolveDocumentPresentation().namespaces,['Property','Lease','Person/Organization','Mandate','Settlement','Maintenance','organization-material']);
assert.deepEqual(resolveAdministrationResidualPolicy().residual_facts,['keys','repairs','deposits','disputes']);
assert.equal(validateRelationCatalog().relations,85);
console.log('domain-descriptors: PASS (85-relation canon, preserved scope/outcomes, ownership, digest and immutable no-authority resources)');
